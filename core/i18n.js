  let _current = 'en';

  function getLanguages() { return LANGUAGES.slice(); }

  function getLanguage(code) {
    return LANGUAGES.find(l => l.code === code) || LANGUAGES[0];
  }

  function t(key, fallback = '') {
    const dict = T[_current] || T.en;
    return dict[key] || (T.en[key]) || fallback || key;
  }

  function getCurrent() { return _current; }
  function getDir() { return getLanguage(_current).dir; }

  async function load() {
    try {
      const stored = await chrome.storage.local.get('language');
      const wanted = stored?.language || '';
      if (LANGUAGES.some(l => l.code === wanted)) {
        _current = wanted;
      } else {
        const nav = String(navigator.language || 'en').slice(0, 2).toLowerCase();
        _current = LANGUAGES.some(l => l.code === nav) ? nav : 'en';
      }
    } catch { _current = 'en'; }
    applyDirection();
    return _current;
  }

  async function set(code) {
    if (!LANGUAGES.some(l => l.code === code)) return;
    _current = code;
    try { await chrome.storage.local.set({ language: code }); } catch {}
    applyDirection();
  }

  function applyDirection() {
    try {
      const html = document.documentElement;
      const body = document.body;
      html.setAttribute('lang', _current);
      // Layout is always LTR. We never flip the whole dashboard for
      // RTL languages — the sidebar stays on the left, the topbar stays
      // on the top, and only text content gets RTL alignment (via CSS
      // rules scoped to .lang-rtl-text, see dashboard.css).
      html.setAttribute('dir', 'ltr');

      if (!body) return;

      // Legacy class cleanup — a previous version added .rtl to <body>
      body.classList.remove('rtl');

      const isRtlText = (_current === 'fa' || _current === 'ar' || _current === 'he');
      body.classList.toggle('lang-rtl-text', isRtlText);

      body.classList.toggle('lang-fa', _current === 'fa');
      body.classList.toggle('lang-ar', _current === 'ar');
    } catch {}
  }

  function apply(root = document) {
    try {
      root.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const attr = el.getAttribute('data-i18n-attr');
        const txt = t(key, el.textContent);
        if (attr) el.setAttribute(attr, txt);
        else el.textContent = txt;
      });
      root.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        el.innerHTML = t(key, el.innerHTML);
      });
      root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'), el.placeholder));
      });
      root.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.setAttribute('title', t(el.getAttribute('data-i18n-title'), el.title));
      });
    } catch {}
  }

  return {
    getLanguages,
    getLanguage,
    getCurrent,
    getDir,
    t,
    load,
    set,
    apply,
    applyDirection
  };
